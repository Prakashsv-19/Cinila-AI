
import {
  Document,
  Packer,
  Paragraph,
  TextRun,
  HeadingLevel,
  AlignmentType,
  Header,
  Footer,
  PageNumber,
  BorderStyle,
} from "docx";

function sanitizeFileName(name: string): string {
  return name
    .replace(/[<>:"/\\|?*]/g, "")
    .replace(/\s+/g, "_")
    .trim();
}

export async function downloadWordDocument(
  projectTitle: string,
  documentTitle: string,
  content: string
) {
  const lines = content.split(/\r?\n/);
  const children: Paragraph[] = [];

  for (const rawLine of lines) {
    const line = rawLine.trim();

    if (!line) {
      children.push(new Paragraph({ text: "" }));
      continue;
    }

    if (line.startsWith("### ")) {
      children.push(
        new Paragraph({
          text: line.replace(/^###\s+/, ""),
          heading: HeadingLevel.HEADING_3,
          spacing: { before: 160, after: 80 },
        })
      );
    } else if (line.startsWith("## ")) {
      children.push(
        new Paragraph({
          text: line.replace(/^##\s+/, ""),
          heading: HeadingLevel.HEADING_2,
          spacing: { before: 240, after: 120 },
        })
      );
    } else if (line.startsWith("# ")) {
      children.push(
        new Paragraph({
          text: line.replace(/^#\s+/, ""),
          heading: HeadingLevel.HEADING_1,
          spacing: { before: 300, after: 150 },
        })
      );
    } else if (/^[-*]\s+/.test(line)) {
      children.push(
        new Paragraph({
          children: [
            new TextRun(line.replace(/^[-*]\s+/, "")),
          ],
          bullet: {
  level: 0,
},
          spacing: { after: 80 },
        })
      );
    } else if (/^\d+[.)]\s+/.test(line)) {
      children.push(
        new Paragraph({
          text: line,
          spacing: { after: 100 },
        })
      );
    } else {
      children.push(
        new Paragraph({
          children: [new TextRun(line)],
          spacing: { after: 100 },
        })
      );
    }
  }

  const doc = new Document({
    creator: "Cinila AI",
    title: documentTitle,
    description: `Professional ${documentTitle} generated by Cinila AI`,
    sections: [
      {
        properties: {},
        headers: {
          default: new Header({
            children: [
              new Paragraph({
                children: [
                  new TextRun({
                    text: "CINILA AI",
                    bold: true,
                    color: "0145F2",
                    size: 20,
                  }),
                  new TextRun({
                    text: "  |  FILMMAKING WORKSPACE",
                    color: "666666",
                    size: 16,
                  }),
                ],
                border: {
                  bottom: {
                    color: "0145F2",
                    style: BorderStyle.SINGLE,
                    size: 6,
                    space: 6,
                  },
                },
              }),
            ],
          }),
        },
        footers: {
          default: new Footer({
            children: [
              new Paragraph({
                alignment: AlignmentType.CENTER,
                children: [
                  new TextRun({
                    text: "Generated with Cinila AI  |  Page ",
                    size: 16,
                    color: "666666",
                  }),
                  new TextRun({
                    children: [PageNumber.CURRENT],
                    size: 16,
                  }),
                ],
              }),
            ],
          }),
        },
        children: [
          new Paragraph({
            alignment: AlignmentType.CENTER,
            spacing: { before: 500, after: 150 },
            children: [
              new TextRun({
                text: "CINILA AI",
                bold: true,
                size: 36,
                color: "0145F2",
              }),
            ],
          }),
          new Paragraph({
            alignment: AlignmentType.CENTER,
            spacing: { after: 200 },
            children: [
              new TextRun({
                text: documentTitle,
                bold: true,
                size: 30,
              }),
            ],
          }),
          new Paragraph({
            alignment: AlignmentType.CENTER,
            spacing: { after: 350 },
            children: [
              new TextRun({
                text: `Project: ${projectTitle}`,
                size: 22,
                color: "666666",
              }),
            ],
          }),
          new Paragraph({
            spacing: { after: 300 },
            border: {
              bottom: {
                color: "0145F2",
                style: BorderStyle.SINGLE,
                size: 8,
                space: 8,
              },
            },
          }),
          ...children,
        ],
      },
    ],
  });

  const blob = await Packer.toBlob(doc);
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");

  link.href = url;
  link.download =
    `${sanitizeFileName(projectTitle)}_${sanitizeFileName(documentTitle)}.docx`;

  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);

  URL.revokeObjectURL(url);
}
